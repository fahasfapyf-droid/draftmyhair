function compileMasterPromptSets(): void {
  for (const set of PROMPT_SETS) {
    const files = getPromptFiles(
      set.sourceDir
    );

    const prompt = readPromptFiles(
      set.sourceDir,
      files
    );

    const version = generateVersion(prompt);

    const output = buildOutput(
      prompt,
      version,
      set
    );

    fs.mkdirSync(
      path.dirname(set.outputFile),
      {
        recursive: true,
      }
    );

    fs.writeFileSync(
      set.outputFile,
      output,
      "utf8"
    );

    console.log(
      `✓ ${set.name.padEnd(16)} | Modules: ${files.length} | Version: ${version}`
    );

    console.log(
      `  Output: ${path.relative(
        ROOT,
        set.outputFile
      )}`
    );

    console.log("");
  }
}

