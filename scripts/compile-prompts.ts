function getPromptFiles(sourceDir: string): string[] {
  if (!fs.existsSync(sourceDir)) {
    throw new Error(`Prompt directory not found:\n${sourceDir}`);
  }

  const files = fs
    .readdirSync(sourceDir)
    .filter((file) => PROMPT_FILE_PATTERN.test(file))
    .sort((a, b) =>
      a.localeCompare(b, undefined, {
        numeric: true,
      })
    );

  if (files.length === 0) {
    throw new Error(
      `No prompt modules found in:\n${sourceDir}`
    );
  }

  return files;
}

function readPromptFiles(
  sourceDir: string,
  files: string[]
): string {
  return files
    .map((file) => {
      const fullPath = path.join(sourceDir, file);

      const content = fs
        .readFileSync(fullPath, "utf8")
        .trim();

      if (!content.length) {
        throw new Error(
          `Prompt file is empty:\n${fullPath}`
        );
      }

      return content;
    })
    .join("\n\n");
}

function escapeTemplateLiteral(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function generateVersion(prompt: string): string {
  return crypto
    .createHash("sha256")
    .update(prompt)
    .digest("hex")
    .substring(0, 12);
}

function buildOutput(
  prompt: string,
  version: string,
  set: PromptSet
): string {
  return `/**
 * ============================================================
 * AUTO-GENERATED FILE
 * ============================================================
 *
 * DO NOT EDIT THIS FILE.
 *
 * Source:
 * generation/${set.name}/
 *
 * Generated by:
 * npm run compile:prompts
 *
 * ============================================================
 */

export const ${set.versionName} = "${version}";

export const ${set.exportName} = \`
${escapeTemplateLiteral(prompt)}
\`;
`;
}

